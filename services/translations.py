def get_current_lang():
    if "lang" not in st.session_state:
        st.session_state["lang"] = "en"
    return st.session_state["lang"]

def t(key, default_text=None):
    lang = get_current_lang()
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    return lang_dict.get(key, TRANSLATIONS["en"].get(key, default_text or key))

def render_language_selector(sidebar=True):
    current = get_current_lang()
    options = ["English", "Italiano"]
    current_index = 0 if current == "en" else 1
    
    container = st.sidebar if sidebar else st
    selected = container.selectbox(
        label="🌐 " + ("Language / Lingua" if current == "en" else "Lingua / Language"),
        options=options,
        index=current_index,
        key="lang_selector"
    )
    new_lang = "en" if selected == "English" else "it"
    if new_lang != current:
        st.session_state["lang"] = new_lang
        st.rerun()
